// canonical orders object fields, preserving array order and every literal value.
// canonical 排序对象字段，保留数组顺序与所有字面值。
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object") return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]));
  return value;
}
const missing = [];
function paths(doc) {
  const fields = [];
  function add(path, text) {
    if (!text || ["cURL", "Python", "JavaScript", "Embeddings", "Rerank", "Responses", "JSON Schema。", "assistant。", "function。"].includes(text)) return;
    const key = byText.get(text);
    if (!key) { missing.push({ slug: doc.slug, path, text }); return; }
    fields.push({ path, key });
  }
  for (const key of ["category", "title", "summary"]) add([key], doc[key]);
  const c = doc.content;
  c.highlights.forEach((text, index) => add(["content", "highlights", index], text));
  add(["content", "notice"], c.notice);
  function params(items, path) {
    items.forEach((param, index) => {
      add([...path, index, "description"], param.description);
      if (param.children) params(param.children, [...path, index, "children"]);
    });
  }
  for (const key of ["headers", "path_params", "query_params", "body_params", "response_fields"]) params(c[key], ["content", key]);
  for (const key of ["request_examples", "response_examples"]) c[key].forEach((example, index) => add(["content", key, index, "label"], example.label));
  c.sections.forEach((section, index) => {
    add(["content", "sections", index, "title"], section.title);
    add(["content", "sections", index, "body"], section.body);
  });
  return fields;
}
