import fs from "node:fs/promises";
import {sha256} from "./apply.mjs";

const raw = await fs.readFile(new URL("./manifest.json", import.meta.url));
const config = JSON.parse(raw);
const output = `// Code generated by scripts/comfyui-localization/sync-metadata.mjs. DO NOT EDIT.
// 代码由 scripts/comfyui-localization/sync-metadata.mjs 生成，请勿手工修改。
package comfyeditor

const localizedSourceCommit = ${JSON.stringify(config.source.commit)}
const localizedSourceArchiveSHA256 = ${JSON.stringify(config.source.archive_sha256)}
const localizedConfigurationSHA256 = ${JSON.stringify(sha256(raw))}

var localizedLocales = map[string]string{
${Object.entries(config.locales).map(([key, value]) => `\t${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n")}
}
`;
const destination = new URL("../../service/aiServeWeaveControlPlane/internal/comfyeditor/localization_version.go", import.meta.url);
if (process.argv.includes("--check")) {
  // Whitespace is gofmt-owned; token text must match the resource source.
  // 空白由 gofmt 处理，标记文本必须与资源唯一来源一致。
  if ((await fs.readFile(destination, "utf8")).replace(/\s/g, "") !== output.replace(/\s/g, "")) throw new Error("Run sync-metadata.mjs and gofmt after changing localization resources");
} else await fs.writeFile(destination, output);
